"""Show two held-out photos and two AC-GAN samples per category."""
import argparse
from pathlib import Path

import torch
from PIL import Image, ImageDraw, ImageFont, ImageOps

from train import DATA_DIR, image_tensor, load_generation_checkpoint, load_split, sample


RUNS = Path(__file__).resolve().parent / "runs"
CHECKPOINT = RUNS / "current" / "model_12000.pt"
OUTPUT = RUNS / "demo"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", type=Path, default=CHECKPOINT)
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR, help="SYSU-Shape dataset directory")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--class-name", help="Generate only this SYSU-Shape category")
    parser.add_argument("--seed", type=int, default=62077, help="Seed for the sampling noise")
    args = parser.parse_args()

    torch.set_num_threads(4)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    generator, config, classes, _ = load_generation_checkpoint(args.checkpoint, device)
    if not config.get("conditional", True):
        parser.error("Choose a conditional AC-GAN checkpoint.")
    if args.class_name and args.class_name not in classes:
        parser.error(f"Choose a category from {', '.join(classes)}.")
    selected = [args.class_name] if args.class_name else classes
    labels = torch.tensor([classes.index(name) for name in selected]).repeat_interleave(2)
    output_dir = args.output or OUTPUT / (args.class_name or "five_classes")
    generated_dir = output_dir / "generated"
    generated_dir.mkdir(parents=True, exist_ok=True)
    split = load_split(args.data_dir)
    framing = config.get("framing", "full64")
    generated = sample(generator, labels, device, noise_seed=args.seed, truncation=1.5)

    board = Image.new("RGB", (764, 104 + 148 * len(selected)), "#f5f6f7")
    draw = ImageDraw.Draw(board)
    heading = ImageFont.load_default(size=27)
    body = ImageFont.load_default(size=18)
    draw.text((22, 15), "SYSU-Shape AC-GAN", font=heading, fill="#172235")
    draw.text((22, 50), "Held-out photographs and class-conditional samples",
              font=body, fill="#455467")
    draw.text((158, 80), "Real validation photos", font=body, fill="#172235")
    draw.text((452, 80), "Generated by AC-GAN", font=body, fill="#172235")

    for row, name in enumerate(selected):
        class_id = split["classes"].index(name)
        photos = [path for path, label in split["validation"] if label == class_id][:2]
        real = [image_tensor(path, framing) for path in photos]
        top = 104 + row * 148
        draw.text((22, top + 55), name, font=body, fill="#172235")
        for column, pixels in enumerate(real):
            paste_tile(board, pixels, 158 + 138 * column, top)
        for column, pixels in enumerate(generated[row * 2:row * 2 + 2]):
            image = paste_tile(board, pixels, 452 + 138 * column, top)
            image.save(generated_dir / f"{name}_{column + 1}.png")

    figure = output_dir / "real_vs_generated.png"
    board.save(figure)
    print(f"Generated {2 * len(selected)} images on {device}.")
    print(f"Open {figure}")


def paste_tile(board, pixels, left, top):
    image = Image.fromarray(pixels.permute(1, 2, 0).numpy())
    tile = ImageOps.contain(image, (128, 128), Image.Resampling.NEAREST)
    board.paste(tile, (left + (128 - tile.width) // 2, top + (128 - tile.height) // 2))
    return image


if __name__ == "__main__":
    main()
